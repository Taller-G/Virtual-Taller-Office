#!/usr/bin/env python3
"""
Splits each base avatar (adam, ash, lucy, nancy) into the aligned layers a
composed avatar is drawn with -- body, hair, top, pants, shoes -- and generates
the skin-tone variants of the body layer.  Every layer but the body is saved in
greyscale so it can be tinted at runtime with Phaser's `setTint()`.

Development only: the result is committed in
apps/client/public/assets/avatars/layers/.  Requires Python 3 and Pillow.

Usage:  python3 tools/split-layers.py
        python3 tools/gen-hair.py          # the other four hair styles
        python3 tools/gen-facial-hair.py   # beards, on top of what this writes

Layout of each layer: 1664x48 px (52 frames of 32x48), the same LimeZu layout as
the full avatars.  The pixels that do not belong to the layer are left
transparent (alpha 0).  The art inside those frames is drawn on a 2x grid (16x24
drawn pixels per frame), which is why everything here works in steps of two.

Layers:
  body        -- skin, face, outlines; EVERYTHING but the parts below.
  hair-short  -- the cropped cut the character is drawn with, greyscale.
  top         -- torso clothing only, greyscale.
  pants       -- the legs, greyscale.
  shoes       -- the feet, greyscale.

The skin variants are generated by remapping the skin colours (a subset of
PROTECTED) with an HSV rotation, in the style of person-avatars.py.  The
outlines and the mouth do not change.

LimeZu's licence allows editing the assets (see docs/asset-licenses.md).
"""
from __future__ import annotations

import colorsys
from pathlib import Path

from PIL import Image

AVATARS_DIR = Path(__file__).resolve().parents[1] / "apps/client/public/assets/avatars"
LAYERS_DIR = AVATARS_DIR / "layers"

FRAME_W, FRAME_H = 32, 48  # one frame of the sprite sheet
ART = 2  # the sheets are 2x art: every drawn pixel is a 2x2 block

# Bounds for the hem the silhouette suggests; the legs never start outside them.
HEM_MIN, HEM_MAX, HEM_DEFAULT = 36, 40, 40

